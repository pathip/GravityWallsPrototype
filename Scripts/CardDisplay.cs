public class CardDisplay : MonoBehaviour
{
    [Header("UI References — drag ?? Inspector")]
    [SerializeField] private Image artworkImage;   // ????????
    [SerializeField] private TextMeshProUGUI cardNameText;   // ?????????
    [SerializeField] private GameObject reversedBadge;  // ???? "Reversed" — toggle active

    private CardInstance currentCard;

    // ?????????????????? Spawn ?????
    public void Setup(CardInstance card)
    {
        currentCard = card;

        if (cardNameText != null)
            cardNameText.text = card.data.cardName;

        // ????? Artwork ??????? ???????? (????????? Token ?????) ??????? Image ???
        if (artworkImage != null)
        {
            if (card.data.artwork != null)
            {
                artworkImage.sprite = card.data.artwork;
                artworkImage.enabled = true;
            }
            else
            {
                artworkImage.enabled = false; // ???????? — ?????????????????????????
            }
        }

        // ???? Badge ??????????????????? (Reversed)
        if (reversedBadge != null)
            reversedBadge.SetActive(card.isReversed);

        // ????????????????? Reversed (180 ????)
        transform.rotation = card.isReversed
            ? Quaternion.Euler(0, 0, 180)
            : Quaternion.identity;
    }

    public CardInstance GetCard() => currentCard;

    // ????????????????? (?????? Button OnClick ??? Prefab ???)
    public void OnCardClicked()
    {
        if (currentCard == null) return;
        Debug.Log($"[CardClick] {currentCard.data.cardName} — {currentCard.GetMeaning()}");
    }
}
